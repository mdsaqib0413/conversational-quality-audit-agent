class AuditReportGenerator:
    """Renders HTML and PDF audit reports."""

    def render_html(self, report: AuditReport) -> str:
        template = Template(REPORT_HTML_TEMPLATE)
        return template.render(report=report)

    def export_pdf(self, report: AuditReport, output_pdf_path: str) -> str:
        """Renders report as PDF using xhtml2pdf."""
        html_content = self.render_html(report)
        out_path = Path(output_pdf_path)
        out_path.parent.mkdir(parents=True, exist_ok=True)

        try:
            from xhtml2pdf import pisa
            with open(out_path, "wb") as pdf_file:
                pisa_status = pisa.CreatePDF(html_content, dest=pdf_file)
            if pisa_status.err:
                logger.error(f"Error creating PDF: {pisa_status.err}")
        except Exception as e:
            logger.warning(f"xhtml2pdf generation issue: {e}. Writing HTML output instead.")
            html_fallback = out_path.with_suffix(".html")
            html_fallback.write_text(html_content, encoding="utf-8")
            return str(html_fallback)

        return str(out_path)

# Singleton
